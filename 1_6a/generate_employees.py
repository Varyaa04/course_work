#!/usr/bin/env python3
import random

# Фиксируем seed для воспроизводимости
random.seed(42)

surnames_male = [
    "Смирнов", "Иванов", "Кузнецов", "Соколов", "Попов", "Лебедев", "Козлов", "Новиков", "Морозов", "Петров",
    "Волков", "Соловьев", "Васильев", "Зайцев", "Павлов", "Семенов", "Голубев", "Виноградов", "Богданов", "Воробьев",
    "Федоров", "Михайлов", "Беляев", "Тарасов", "Белов", "Комаров", "Орлов", "Киселев", "Макаров", "Андреев",
    "Ковалев", "Ильин", "Гусев", "Титов", "Кузьмин", "Кудрявцев", "Баранов", "Куликов", "Алексеев", "Степанов",
    "Яковлев", "Сорокин", "Сергеев", "Романов", "Захаров", "Борисов", "Королев", "Герасимов", "Пономарев", "Григорьев"
]

surnames_female = [s + "а" for s in surnames_male if s[-1] != "й"] + [s + "а" for s in surnames_male if s[-1] == "й"]
all_surnames = surnames_male + surnames_female

positions = ["главный инженер", "ведущий инженер", "старший инженер", "инженер", "техник"]

for i in range(50000):
    surname = random.choice(all_surnames)
    position = random.choice(positions)
    print(f"{surname:<15} {position}")
